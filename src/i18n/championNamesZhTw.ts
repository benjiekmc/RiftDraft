export function getChampionDisplayName(
  championOrId: Pick<ChampionDefinition, 'id' | 'name'> | string,
  lang: AppLanguage,
  fallbackName?: string
): string {
  const id = typeof championOrId === 'string' ? championOrId : championOrId.id;
  const enName =
    typeof championOrId === 'string' ? fallbackName ?? championOrId : championOrId.name;

  if (lang === 'zh-TW') {
    return CHAMPION_NAMES_ZH_TW[id] ?? enName;
  }
  return enName;
}
